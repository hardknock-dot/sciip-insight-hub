import { createFileRoute } from "@tanstack/react-router";
import { useQuery, useSuspenseQuery } from "@tanstack/react-query";
import { useState } from "react";
import { forecastQuery, partsQuery } from "@/services/queries";
import { PageHeader, Panel, BackendNote, EmptyState } from "@/components/shared/Panel";
import { MetricGrid } from "@/components/shared/MetricCard";
import { ForecastChart } from "@/components/charts/TrendChart";
import { DataTable, type Column } from "@/components/shared/DataTable";
import { fmtPct, fmtQty } from "@/lib/format";

export const Route = createFileRoute("/forecast")({
  head: () => ({
    meta: [
      { title: "Forecast — SCIIP" },
      {
        name: "description",
        content:
          "Per-part demand forecasts with accuracy and confidence, served by the backend forecasting service.",
      },
      { property: "og:title", content: "Forecast — SCIIP" },
      { property: "og:description", content: "Demand forecasts per part with accuracy tracking." },
    ],
  }),
  loader: async ({ context }) => {
    await context.queryClient.ensureQueryData(partsQuery);
  },
  component: ForecastPage,
});

function ForecastPage() {
  const { data: parts } = useSuspenseQuery(partsQuery);
  const [partCode, setPartCode] = useState(parts[0]?.partCode ?? "");
  const { data: forecast } = useQuery({
    ...forecastQuery(partCode),
    enabled: partCode.length > 0,
  });

  type Point = { period: string; forecastQty: number; actualQty: number | null };
  const cols: Column<Point>[] = [
    { key: "period", header: "Period", cell: (p) => p.period },
    { key: "forecastQty", header: "Forecast qty", align: "right", cell: (p) => fmtQty(p.forecastQty) },
    { key: "actualQty", header: "Actual qty", align: "right", cell: (p) => (p.actualQty == null ? "—" : fmtQty(p.actualQty)) },
    {
      key: "delta",
      header: "Variance",
      align: "right",
      cell: (p) =>
        p.actualQty == null ? "—" : `${p.actualQty - p.forecastQty > 0 ? "+" : ""}${fmtQty(p.actualQty - p.forecastQty)}`,
    },
  ];

  return (
    <>
      <PageHeader
        eyebrow="Intelligence layer"
        title="Forecast"
        description="The UI never computes a forecast. It renders exactly what the forecasting service returns for the selected part."
        actions={
          <select
            value={partCode}
            onChange={(e) => setPartCode(e.target.value)}
            className="h-9 rounded-md border border-input bg-surface px-2 text-sm outline-none focus:border-ring"
          >
            {parts.map((p) => (
              <option key={p.id} value={p.partCode}>
                {p.partCode} — {p.description}
              </option>
            ))}
          </select>
        }
      />

      {forecast ? (
        <>
          <MetricGrid
            metrics={[
              { key: "horizon", label: "Horizon", value: `${forecast.horizonMonths} months` },
              {
                key: "accuracy",
                label: "Backtest accuracy",
                value: forecast.accuracyPct == null ? "—" : fmtPct(forecast.accuracyPct),
                hintTone: "success",
                hint: "Against realised demand",
              },
              {
                key: "confidence",
                label: "Confidence",
                value: forecast.confidencePct == null ? "Backend" : fmtPct(forecast.confidencePct),
                hint: "Supplied by the model",
              },
              {
                key: "model",
                label: "Model",
                value: forecast.model?.name ?? "Pending",
                hint: forecast.model ? `v${forecast.model.version}` : "Awaiting Python service",
              },
            ]}
          />

          <Panel title={`Forecast vs. actual — ${forecast.partCode}`}>
            <ForecastChart data={forecast.points} />
          </Panel>

          {forecast.explanation && (
            <Panel title="Model reasoning" subtitle={`Generated by ${forecast.explanation.generatedBy}`}>
              <p className="text-sm">{forecast.explanation.summary}</p>
              <ul className="mt-2 space-y-1 text-xs text-muted-foreground">
                {forecast.explanation.reasoning.map((r, i) => (
                  <li key={i}>• {r}</li>
                ))}
              </ul>
            </Panel>
          )}

          <Panel title="Forecast points" bodyClassName="p-0">
            <DataTable columns={cols} rows={forecast.points} rowKey={(p) => p.period} />
          </Panel>
        </>
      ) : (
        <EmptyState message="Select a part to load its forecast." />
      )}

      <BackendNote>
        Swap `getForecast(partCode)` for the FastAPI endpoint; the selector, chart, table and
        reasoning panel need no changes.
      </BackendNote>
    </>
  );
}
